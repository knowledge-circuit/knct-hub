#!/usr/bin/env node
// Scans cli/kpatches/*.md and writes cli/src/kpatches.generated.ts —
// a static module that imports each kpatch body as text and exports
// a typed list. Run before esbuild so the bundle inlines everything.

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const kpatchDir = join(root, "kpatches");
const outFile = join(root, "src", "kpatches.generated.ts");

const files = readdirSync(kpatchDir)
  .filter((f) => f.endsWith(".md"))
  .sort();

const imports = files
  .map((f, i) => `import k${i} from "../kpatches/${f}";`)
  .join("\n");

const entries = files
  .map((f, i) => `  { filename: ${JSON.stringify(f)}, body: k${i} },`)
  .join("\n");

const src = `// Generated by scripts/build-manifest.mjs. Do not edit.
${imports}

export type BundledKpatch = { filename: string; body: string };

export const BUNDLED_KPATCHES: BundledKpatch[] = [
${entries}
];
`;

writeFileSync(outFile, src);
console.log(`wrote ${outFile} (${files.length} kpatches)`);
